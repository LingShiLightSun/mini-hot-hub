const BUCKET_MS = 10 * 60 * 1000 // 10 分钟一桶，与榜单刷新节奏对齐

// 用种子做确定性洗牌（xorshift32），同一 lap 洗出的顺序固定，跨访客一致
function seededShuffle<T>(arr: T[], seed: number): T[] {
  const a = arr.slice()
  let s = (seed >>> 0) + 1 // +1 保证 seed=0 与 seed=1 得到不同序列
  const rand = () => {
    s ^= s << 13
    s ^= s >>> 17
    s ^= s << 5
    s >>>= 0
    return s / 4294967296
  }
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1))
    const t = a[i]
    a[i] = a[j]
    a[j] = t
  }
  return a
}

// 给定时间戳，返回该时刻应展示的金句
export function getQuoteAt(ts: number): string {
  const len = QUOTES.length
  const bucket = Math.floor(ts / BUCKET_MS)
  const lap = Math.floor(bucket / len) // 第几圈：每走完一圈换一种排列
  const pos = bucket % len // 这一圈里的第几句
  return seededShuffle(QUOTES, lap)[pos]
}
